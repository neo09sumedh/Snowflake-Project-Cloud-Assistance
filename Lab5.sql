SELECT
    CLOUD_PROVIDER,
    SUM(TOTAL_PROJECT_COST) AS TOTAL_PROJECT_COST
FROM VW_PROJECT_COST
GROUP BY CLOUD_PROVIDER
ORDER BY TOTAL_PROJECT_COST DESC;

SELECT
    OWNER_NAME,
    SUM(TOTAL_PROJECT_COST) AS TOTAL_PROJECT_COST
FROM VW_PROJECT_COST
