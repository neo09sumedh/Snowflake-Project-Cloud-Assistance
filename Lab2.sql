SELECT
    P.PROJECT_NAME,
    C.CLOUD_PROVIDER,
    O.OWNER_NAME,
    P.PROJECT_STATUS
FROM DIM_PROJECT P
INNER JOIN DIM_CLOUD C
    ON P.CLOUD_ID = C.CLOUD_ID
INNER JOIN DIM_OWNER O
    ON P.OWNER_ID = O.OWNER_ID;

/*Analytical Query*/
    SELECT
    P.PROJECT_NAME,

    SUM(
        F.COMPUTE_COST +
        F.STORAGE_COST +
        F.NETWORK_COST
    ) AS TOTAL_COST

FROM FACT_PROJECT_COST F

INNER JOIN DIM_PROJECT P
        ON F.PROJECT_ID = P.PROJECT_ID

GROUP BY P.PROJECT_NAME

ORDER BY TOTAL_COST DESC;


/*2*/

SELECT
    C.CLOUD_PROVIDER,

    SUM(
        F.COMPUTE_COST +
        F.STORAGE_COST +
        F.NETWORK_COST
    ) AS TOTAL_COST

FROM FACT_PROJECT_COST F

INNER JOIN DIM_PROJECT P
        ON F.PROJECT_ID = P.PROJECT_ID

INNER JOIN DIM_CLOUD C
        ON P.CLOUD_ID = C.CLOUD_ID

GROUP BY C.CLOUD_PROVIDER

ORDER BY TOTAL_COST DESC;

/*3*/

SELECT
    O.OWNER_NAME,

    SUM(
        F.COMPUTE_COST +
        F.STORAGE_COST +
        F.NETWORK_COST
    ) AS TOTAL_COST

FROM FACT_PROJECT_COST F

INNER JOIN DIM_PROJECT P
        ON F.PROJECT_ID = P.PROJECT_ID

INNER JOIN DIM_OWNER O
        ON P.OWNER_ID = O.OWNER_ID

GROUP BY O.OWNER_NAME

ORDER BY TOTAL_COST DESC;


/*Buisness View presnted for Semantic layer in next lab3*/

CREATE OR REPLACE VIEW VW_PROJECT_COST AS
SELECT

    P.PROJECT_ID,
    P.PROJECT_NAME,
    P.PROJECT_STATUS,

    C.CLOUD_PROVIDER,
    C.REGION,

    O.OWNER_NAME,
    O.BUSINESS_UNIT,

    F.COST_MONTH,

    F.COMPUTE_COST,
    F.STORAGE_COST,
    F.NETWORK_COST,

    (
        F.COMPUTE_COST +
        F.STORAGE_COST +
        F.NETWORK_COST
    ) AS TOTAL_PROJECT_COST

FROM FACT_PROJECT_COST F

INNER JOIN DIM_PROJECT P
        ON F.PROJECT_ID = P.PROJECT_ID

INNER JOIN DIM_CLOUD C
        ON P.CLOUD_ID = C.CLOUD_ID

INNER JOIN DIM_OWNER O
        ON P.OWNER_ID = O.OWNER_ID;

SELECT *
FROM VW_PROJECT_COST
ORDER BY PROJECT_ID,COST_MONTH;

